/* Offline input-only sketch generator. Generated telemetry uses the ASCII gateway adapter. */
(function (exports) {
  function generate(blocks) {
    if (!blocks.length) throw Error("Add an input block.");
    const channels=new Set(),pins=new Set(),declarations=[],reports=[];
    for (const block of blocks) {
      if (!/^[a-z][a-z0-9_]{0,23}$/.test(block.channel) || channels.has(block.channel))
        throw Error("Use a unique lowercase channel name.");
      const analog=block.type==="oes_analog";
      if (!analog && block.type!=="oes_button") throw Error("Unknown input block.");
      if (!(analog ? /^A[0-5]$/ : /^(?:[2-9]|1[0-2])$/).test(block.pin) || pins.has(block.pin))
        throw Error("Pin is unavailable or already used.");
      channels.add(block.channel);pins.add(block.pin);
      if (!analog) declarations.push("  pinMode("+block.pin+", INPUT_PULLUP);");
      const value=analog ? "analogRead("+block.pin+")" : "(digitalRead("+block.pin+")==LOW ? 1 : 0)";
      reports.push('  Serial.print(F("'+block.channel+' ")); Serial.println('+value+');');
    }
    return ["// Generated by OpenExhibit Studio. Use the gateway ASCII adapter.","void setup() {","  Serial.begin(115200);",...declarations,"}","void loop() {","  static unsigned long last=0;","  if (millis()-last<100) return;","  last=millis();",...reports,"}",""].join("\n");
  }
  exports.generateExhibitSketch=generate;
})(typeof module==="object" ? module.exports : window);
