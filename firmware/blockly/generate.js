/* Turns firmware blocks into an Arduino sketch that prints "channel value" lines at 115200 baud.
   OpenExhibit's gateway reads these lines with its ASCII adapter (profile: serial-text.json).
   Works in the browser (window.generateExhibitSketch) and in Node (module.exports) for tests. */
(function (exports) {
  'use strict';

  const BOARDS = {
    uno: {label: 'Arduino Uno', digital: range(2, 13), analog: range(0, 5).map(n => 'A' + n)},
    nano: {label: 'Arduino Nano', digital: range(2, 13), analog: range(0, 7).map(n => 'A' + n)},
    mega: {label: 'Arduino Mega 2560', digital: range(2, 53), analog: range(0, 15).map(n => 'A' + n)},
  };
  const KINDS = {
    oes_analog: {pins: ['analog']},
    oes_button: {pins: ['digital']},
    oes_switch: {pins: ['digital']},
    oes_distance: {pins: ['digital', 'digital']},
  };

  function range(from, to) {
    const out = [];
    for (let n = from; n <= to; n++) out.push(String(n));
    return out;
  }

  /** blocks: [{type, channel, pin, pin2?}] in workspace order. options: {board, interval} */
  function generate(blocks, options = {}) {
    const board = BOARDS[options.board || 'uno'];
    if (!board) throw Error('Unknown board.');
    const interval = Math.round(Number(options.interval || 100));
    if (!(interval >= 20 && interval <= 5000)) throw Error('Choose a sample interval from 20 to 5000 ms.');
    if (!blocks.length) throw Error('Drag at least one sensor block into the workspace.');

    const channels = new Set(), pins = new Set();
    const setup = [], helpers = [], reports = [];
    for (const block of blocks) {
      const kind = KINDS[block.type];
      if (!kind) throw Error('Unknown block: ' + block.type);
      if (!/^[a-z][a-z0-9_]{0,23}$/.test(block.channel || ''))
        throw Error('Channel names use lowercase letters, digits and _ (for example dial or door_1).');
      if (channels.has(block.channel)) throw Error('Channel "' + block.channel + '" is used twice.');
      channels.add(block.channel);
      const used = kind.pins.length === 2 ? [block.pin, block.pin2] : [block.pin];
      used.forEach((pin, i) => {
        const allowed = kind.pins[i] === 'analog' ? board.analog : board.digital;
        if (!allowed.includes(String(pin))) throw Error('Pin ' + pin + ' is not available on the ' + board.label + ' for this block.');
        if (pins.has(String(pin))) throw Error('Pin ' + pin + ' is used twice.');
        pins.add(String(pin));
      });

      const report = expr => reports.push('  Serial.print(F("' + block.channel + ' ")); Serial.println(' + expr + ');');
      if (block.type === 'oes_analog') {
        report('analogRead(' + block.pin + ')');
      } else if (block.type === 'oes_button') {
        setup.push('  pinMode(' + block.pin + ', INPUT_PULLUP);  // button between pin and GND');
        report('digitalRead(' + block.pin + ') == LOW ? 1 : 0');
      } else if (block.type === 'oes_switch') {
        setup.push('  pinMode(' + block.pin + ', INPUT);  // sensor output drives the pin HIGH when active');
        report('digitalRead(' + block.pin + ') == HIGH ? 1 : 0');
      } else if (block.type === 'oes_distance') {
        const fn = 'distance_' + block.channel;
        setup.push('  pinMode(' + block.pin + ', OUTPUT);  // HC-SR04 TRIG', '  pinMode(' + block.pin2 + ', INPUT);   // HC-SR04 ECHO');
        helpers.push(
          '// Distance in cm from an HC-SR04 (0 when nothing echoes back within ~4 m).',
          'long ' + fn + '() {',
          '  digitalWrite(' + block.pin + ', LOW); delayMicroseconds(2);',
          '  digitalWrite(' + block.pin + ', HIGH); delayMicroseconds(10);',
          '  digitalWrite(' + block.pin + ', LOW);',
          '  unsigned long echo = pulseIn(' + block.pin2 + ', HIGH, 25000UL);',
          '  return echo ? echo / 58 : 0;',
          '}',
          '');
        report(fn + '()');
      }
    }
    return [
      '// Generated by OpenExhibit Studio for the ' + board.label + '.',
      '// Prints "channel value" lines; in Studio → Hardware choose',
      '// "Any Arduino or ESP32 sketch that prints name value lines" and set the inputs to: ' + [...channels].join(', ') + '.',
      '',
      ...helpers,
      'void setup() {',
      '  Serial.begin(115200);',
      ...setup,
      '}',
      '',
      'void loop() {',
      '  static unsigned long last = 0;',
      '  if (millis() - last < ' + interval + 'UL) return;',
      '  last = millis();',
      ...reports,
      '}',
      '',
    ].join('\n');
  }

  exports.generateExhibitSketch = generate;
  exports.EXHIBIT_BOARDS = BOARDS;
})(typeof module === 'object' ? module.exports : window);
